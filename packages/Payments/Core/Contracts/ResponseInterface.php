<?php

declare(strict_types=1);

namespace iEXPackages\Payments\Core\Contracts;

/**
 * Базовый интерфейс ответа платёжного шлюза.
 *
 * Минимальный контракт:
 *  - статусы успешности/ожидания/отмены/ошибки,
 *  - доступ к данным ответа и входным параметрам.
 *
 * Всё остальное (банк, номер счёта, статус, сумма, идентификаторы и т.п.) —
 * НЕ жёсткая часть интерфейса, а рекомендованные методы, которые
 * реализуются в AbstractResponse и/или конкретных Response-классах.
 *
 * Для удобства IDE и статического анализа ключевые методы описаны через
 *
 * @method string getStatus()         Статус операции в терминах платёжного шлюза ("paid", "pending", ...)
 * @method string getAmount()         Сумма операции (строка)
 * @method string getCurrency()       Код валюты операции ("USD", "USDT", ...)
 * @method string getExternalId()     Внешний ID операции в системе шлюза
 * @method string getOrderId()        Внутренний ID заказа/заявки в твоей системе
 * @method mixed   getTransactionId()  Transaction ID, с которым MERCHANT инициировал операцию
 * @method string getResponseCode()   Код ответа шлюза ("00", "ERR", ...)
 * @method string getErrorMessage()   Человекочитаемый текст ошибки
 * @method string getAccountNumber()  Номер счёта/адрес/карты, выданный шлюзом
 * @method string getAccountTag()     Дополнительный тег/label/memo/FIO
 * @method string getLabel()          Произвольная метка/название
 * @method string getSecondaryExternalId() Второй внешний ID от шлюза
 * @method string getBankName()       Название банка (если применимо)
 */
interface ResponseInterface
{
    // ---------------------------------------------------------------------
    //  СТАТУС ОПЕРАЦИИ
    // ---------------------------------------------------------------------

    /**
     * Проверяет, завершилась ли операция УСПЕШНО.
     */
    public function isSuccessful(): bool;

    /**
     * Проверяет, находится ли операция в СОСТОЯНИИ ОЖИДАНИЯ (pending/processing/...).
     */
    public function isPending(): bool;

    /**
     * Проверяет, является ли операция ОТМЕНЁННОЙ.
     */
    public function isCancelled(): bool;

    /**
     * Проверяет, является ли операция НЕУСПЕШНОЙ (ошибка).
     */
    public function isFailure(): bool;

    // ---------------------------------------------------------------------
    //  ДАННЫЕ
    // ---------------------------------------------------------------------

    /**
     * Сырой ответ сервера (для совместимости, отладочных целей).
     */
    public function getRaw(): mixed;

    /**
     * Нормализованные данные ответа (данные сервера).
     *
     * Это именно то, что вернул шлюз (обычно JSON → массив).
     */
    public function getData(): array;

    /**
     * Входные параметры запроса (payload), который был отправлен в шлюз.
     */
    public function getQuery(): array;

    // ---------------------------------------------------------------------
    //  ОБОБЩЁННОЕ ПРЕДСТАВЛЕНИЕ
    // ---------------------------------------------------------------------

    /**
     * Универсальное представление ответа в виде массива.
     *
     * Удобно для:
     *  - логов;
     *  - отдачи через API;
     *  - отладки.
     */
    public function toArray(): array;
}
